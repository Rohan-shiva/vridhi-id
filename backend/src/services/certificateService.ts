import PDFDocument from 'pdfkit';
import { ICertificateRecord } from '../models/types';
import { dbStore } from '../models/store';

export class CertificateService {
  static async generateCertificatePdf(cert: ICertificateRecord): Promise<Buffer> {
    return new Promise((resolve, reject) => {
      const doc = new PDFDocument({
        size: 'A4',
        margin: 40
      });
      const buffers: Buffer[] = [];

      doc.on('data', chunk => buffers.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(buffers)));
      doc.on('error', err => reject(err));

      // Header Bar
      doc.rect(40, 40, doc.page.width - 80, 80).fill('#0f2b5c');
      doc.fillColor('#ffffff')
         .fontSize(22)
         .font('Helvetica-Bold')
         .text('VRIDHI-ID (वृद्धि-ID)', 55, 55, { align: 'center' });
      doc.fontSize(12)
         .font('Helvetica')
         .text('Assistive Multimodal Digital Life Certificate Portal', { align: 'center' });

      // Prominent Watermark / Notice as required by prompt
      doc.rect(40, 130, doc.page.width - 80, 45).fill('#fff3cd');
      doc.fillColor('#856404')
         .fontSize(10)
         .font('Helvetica-Bold')
         .text('NOTICE: DEMONSTRATION LIFE CERTIFICATE RECORD', 55, 140, { align: 'center' });
      doc.font('Helvetica')
         .fontSize(9)
         .text('This document is generated by the Vridhi-ID assistance prototype for demonstration and process assistance. Official statutory issuance requires authorized government gateway sanction.', { align: 'center' });

      // Certificate Details Box
      doc.rect(40, 190, doc.page.width - 80, 320).strokeColor('#cccccc').lineWidth(1).stroke();

      const startY = 215;
      const col1 = 60;
      const col2 = 240;
      const rowGap = 32;

      const fields = [
        ['Certificate ID:', cert.certificateNumber],
        ['Pensioner Name:', cert.pensionerName],
        ['PPO Number:', cert.ppoNumber],
        ['Disbursing Agency:', cert.disbursingAgency],
        ['Date of Issuance:', new Date(cert.issuedAt).toLocaleDateString('en-IN', { day: '2-digit', month: 'long', year: 'numeric' })],
        ['Validity Period:', `Until ${new Date(cert.validUntil).toLocaleDateString('en-IN', { day: '2-digit', month: 'long', year: 'numeric' })}`],
        ['Verification Status:', 'DIGITALLY VERIFIED (CHECKS PASSED)'],
        ['Assistance Mode:', 'Voice-First AI Multimodal Verification']
      ];

      fields.forEach(([label, val], idx) => {
        const y = startY + idx * rowGap;
        doc.fillColor('#333333').font('Helvetica-Bold').fontSize(11).text(label, col1, y);
        doc.fillColor('#0f2b5c').font('Helvetica').fontSize(11).text(val, col2, y);
      });

      // Digital Sign / Security Stamp
      doc.rect(40, 530, doc.page.width - 80, 90).fill('#f8f9fa');
      doc.fillColor('#28a745').font('Helvetica-Bold').fontSize(12).text('✔ BIOMETRIC INTEGRITY VERIFIED', 60, 545);
      doc.fillColor('#555555').font('Helvetica').fontSize(9)
         .text('Presentation attack detection (PAD), face matching against enrolled pension records, speaker verification, and dynamic optical challenge tokens confirmed genuine living presentation.', 60, 565, { width: 480 });

      // Footer
      doc.fillColor('#888888').fontSize(8)
         .text(`System Generated by Vridhi-ID Platform. Application ID: ${cert.applicationId}. Timestamp: ${new Date().toISOString()}`, 40, doc.page.height - 40, { align: 'center' });

      doc.end();
    });
  }

  static async issueCertificateForApplication(applicationId: string): Promise<ICertificateRecord> {
    const app = dbStore.findApplicationById(applicationId);
    if (!app) throw new Error("Application not found");

    const existing = dbStore.findCertificateByAppId(applicationId);
    if (existing) return existing;

    const certNum = `DLC-${new Date().getFullYear()}${String(new Date().getMonth()+1).padStart(2, '0')}-${Math.floor(1000 + Math.random() * 9000)}`;
    const issuedAt = new Date().toISOString();
    const validUntil = new Date(Date.now() + 365 * 24 * 60 * 60 * 1000).toISOString(); // 1 year validity

    const certRecord: ICertificateRecord = {
      id: `cert-${Date.now()}`,
      certificateNumber: certNum,
      applicationId: app.id,
      userId: app.userId,
      pensionerName: app.pensionerName,
      ppoNumber: app.ppoNumber,
      disbursingAgency: app.disbursingAgency,
      issuedAt,
      validUntil,
      status: 'valid',
      isDemonstrationOnly: true
    };

    const pdfBuffer = await this.generateCertificatePdf(certRecord);
    certRecord.pdfBase64 = pdfBuffer.toString('base64');

    dbStore.saveCertificate(certRecord);
    
    // Update application state
    app.status = 'approved';
    dbStore.saveApplication(app);

    dbStore.logAction({
      action: 'CERTIFICATE_ISSUED',
      actorId: app.userId,
      details: { certificateNumber: certNum, applicationId: app.id }
    });

    return certRecord;
  }
}
